// Builds the app's brand assets from the logo master (design/mlch-logo.svg):
//   public/brand/icon.svg       the rounded amber square, cropped
//   public/brand/wordmark.svg   the "mlch" lettering alone
//   public/brand/scribble-*.svg the two scribbles, as open strokes
//   src/components/brand/scribbles.ts  scribble paths for the interface
//   electron/icon.png           1024px app icon on Apple's grid (824px body)
// Run: node scripts/brand-assets.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { svgPathBbox } from "svg-path-bbox";

const root = path.resolve(import.meta.dirname, "..");
const master = fs.readFileSync(path.join(root, "design", "mlch-logo.svg"), "utf8");
const paths = [...master.matchAll(/<path([^>]*)\/>/g)].map((m) => {
  const attrs = m[1];
  const get = (name) => attrs.match(new RegExp(`${name}="([^"]*)"`))?.[1];
  return { d: get(" d") ?? attrs.match(/ d="([^"]*)"/)[1], fill: get("fill"), stroke: get("stroke"), width: get("stroke-width"), opacity: get("fill-opacity") };
});
const square = paths.find((p) => p.fill === "#ffc000");
const wordmark = paths.find((p) => p.fill === "#000000" && p.opacity !== "0.0" && p.d.length > 4000);
const scribbles = paths.filter((p) => p.stroke === "#000000");

const box = (d, pad = 0) => {
  const [x0, y0, x1, y1] = svgPathBbox(d);
  return [x0 - pad, y0 - pad, x1 - x0 + pad * 2, y1 - y0 + pad * 2];
};
const svg = (viewBox, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox.map((n) => n.toFixed(2)).join(" ")}">${body}</svg>\n`;

const [sx, sy, sw, sh] = box(square.d);
const icon = svg([sx, sy, sw, sh], [
  `<path fill="#FFC000" d="${square.d}"/>`,
  `<path fill="#000" d="${wordmark.d}"/>`,
  ...scribbles.map((p) => `<path fill="none" stroke="#000" stroke-width="${p.width}" stroke-linecap="round" stroke-linejoin="round" d="${p.d}"/>`),
].join(""));
fs.writeFileSync(path.join(root, "public/brand/icon.svg"), icon);
fs.writeFileSync(path.join(root, "public/brand/wordmark.svg"), svg(box(wordmark.d, 1), `<path fill="#000" d="${wordmark.d}"/>`));
scribbles.forEach((p) => {
  const name = box(p.d)[1] < sy + sh / 2 ? "top" : "bottom";
  fs.writeFileSync(
    path.join(root, `public/brand/scribble-${name}.svg`),
    svg(box(p.d, 6), `<path fill="none" stroke="#000" stroke-width="${p.width}" stroke-linecap="round" stroke-linejoin="round" d="${p.d}"/>`),
  );
});

// The scribbles as data, for the animated motif in the interface.
const scribbleData = Object.fromEntries(scribbles.map((p) => {
  const [x, y, w, h] = box(p.d, 6);
  const name = box(p.d)[1] < sy + sh / 2 ? "top" : "bottom";
  return [name, { d: p.d, viewBox: [x, y, w, h].map((n) => Number(n.toFixed(2))).join(" ") }];
}));
fs.writeFileSync(
  path.join(root, "src/components/brand/scribbles.ts"),
  `// Generated by scripts/brand-assets.mjs from design/mlch-logo.svg. Do not edit.\nexport const SCRIBBLES = ${JSON.stringify(scribbleData, null, 2)} as const;\n`,
);

// macOS app icon: body 824/1024 centred, soft shadow below.
const body = await sharp(Buffer.from(icon)).resize(824, 824).png().toBuffer();
const shadow = await sharp({ create: { width: 1024, height: 1024, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite([{ input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect x="100" y="112" width="824" height="824" rx="185" fill="black" opacity="0.28"/></svg>`), blend: "over" }])
  .blur(14).png().toBuffer();
await sharp(shadow).composite([{ input: body, left: 100, top: 92 }]).png().toFile(path.join(root, "electron/icon.png"));
console.log("brand assets written");

// Menu bar icons (macOS template images: black on transparent, 18pt square, @1x and @2x):
// the app icon's rounded square with the lettering's "m" cut out; while listening, a dot cut into its corner.
{
  const word = fs.readFileSync(path.join(root, "public/brand/wordmark.svg"), "utf8");
  const m = word.match(/ d="([^"]+)"/)[1].match(/[Mm][^Mm]*/g)[0];
  const [mx, my, mw, mh] = box(m);
  const size = 100;
  const inset = 11;
  const glyph = 56;
  const scale = glyph / Math.max(mw, mh);
  const tx = (size - mw * scale) / 2 - mx * scale;
  const ty = (size - mh * scale) / 2 - my * scale + 3;
  const square = `<rect x="${inset}" y="${inset}" width="${size - inset * 2}" height="${size - inset * 2}" rx="20" fill="#fff"/>`;
  const letter = `<path transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${scale.toFixed(4)})" fill="#000" d="${m}"/>`;
  const icon = (dot) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><defs><mask id="k">${square}${letter}${dot ? `<circle cx="${size - inset - 4}" cy="${inset + 4}" r="24" fill="#000"/>` : ""}</mask></defs><rect width="${size}" height="${size}" fill="#000" mask="url(#k)"/>${dot ? `<circle cx="${size - inset - 4}" cy="${inset + 4}" r="15" fill="#000"/>` : ""}</svg>`;
  for (const [name, dot] of [["trayTemplate", false], ["trayListeningTemplate", true]]) {
    for (const scale2 of [1, 2]) {
      await sharp(Buffer.from(icon(dot)), { density: 300 }).resize(18 * scale2, 18 * scale2).png().toFile(path.join(root, "electron", `${name}${scale2 === 2 ? "@2x" : ""}.png`));
    }
  }
}

// The disk image window (electron-builder.yml dmg): paper, with a marker arrow from the app to Applications.
// Icons sit at (140, 190) and (400, 190) in a 540x380 window.
{
  const background = (scale) => `<svg xmlns="http://www.w3.org/2000/svg" width="${540 * scale}" height="${380 * scale}" viewBox="0 0 540 380"><rect width="540" height="380" fill="#FCFCFA"/><g fill="none" stroke="#000" stroke-width="4" stroke-linecap="round" stroke-linejoin="round"><path d="M222 196 C 250 178, 290 176, 318 190"/><path d="M302 176 L 320 191 L 299 201"/></g></svg>`;
  for (const scale of [1, 2]) {
    await sharp(Buffer.from(background(scale))).png().toFile(path.join(root, "build", `background${scale === 2 ? "@2x" : ""}.png`));
  }
}
